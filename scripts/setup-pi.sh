#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

fail() {
  echo "ERROR: $*" >&2
  exit 1
}

random_hex() {
  od -An -N32 -tx1 /dev/urandom | tr -d ' \n'
}

ARCH="$(uname -m)"
case "$ARCH" in
  aarch64|arm64|x86_64|amd64) ;;
  armv7l|armv6l)
    fail "OpenRabbit requires a 64-bit OS. This host reports ${ARCH}; install 64-bit Raspberry Pi OS."
    ;;
  *)
    fail "Unsupported architecture: ${ARCH}. Use 64-bit ARM64 or x86_64."
    ;;
esac

command -v docker >/dev/null 2>&1 || fail "Docker is not installed. Install Docker Engine and the Compose plugin first."
docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is required (docker compose, not docker-compose)."
command -v curl >/dev/null 2>&1 || fail "curl is required for the health check."

FIRST_RUN=0
if [[ -f .env ]]; then
  echo ".env already exists; leaving it unchanged."
else
  FIRST_RUN=1
  read -r -p "Public dashboard/webhook URL [http://127.0.0.1:3847]: " PUBLIC_URL
  PUBLIC_URL="${PUBLIC_URL:-http://127.0.0.1:3847}"
  if [[ ! "$PUBLIC_URL" =~ ^https?:// ]]; then
    fail "OPENRABBIT_PUBLIC_URL must start with http:// or https://"
  fi

  ADMIN_TOKEN="$(random_hex)"
  GITHUB_SECRET="$(random_hex)"
  GITLAB_SECRET="$(random_hex)"
  BITBUCKET_SECRET="$(random_hex)"
  FORGEJO_SECRET="$(random_hex)"
  umask 077
  cat > .env <<EOF
# Generated by scripts/setup-pi.sh. Keep this file private.
PORT=3847
HOST=0.0.0.0
OPENRABBIT_BIND_ADDRESS=127.0.0.1
OPENRABBIT_PUBLIC_URL=${PUBLIC_URL}
OPENRABBIT_ADMIN_TOKEN=${ADMIN_TOKEN}
OPENRABBIT_DATA_DIR=./data
OPENRABBIT_MAX_BODY_BYTES=2097152

OPENRABBIT_ASYNC_WEBHOOKS=true
OPENRABBIT_JOB_CONCURRENCY=1
OPENRABBIT_JOB_MAX_ATTEMPTS=3
OPENRABBIT_RETRY_DELAY_MS=1000
OPENRABBIT_DOCKER_TARGET=lite

CLOUDFLARE_TUNNEL_TOKEN=

OPENRABBIT_LLM_PROVIDER=auto
OPENRABBIT_LLM_MODEL=
OPENAI_API_KEY=
OPENAI_BASE_URL=https://api.openai.com/v1
ANTHROPIC_API_KEY=
GEMINI_API_KEY=
OLLAMA_BASE_URL=http://host.docker.internal:11434
OLLAMA_MODEL=qwen2.5-coder:7b

GITHUB_TOKEN=
GITHUB_WEBHOOK_SECRET=${GITHUB_SECRET}
GITHUB_API_URL=https://api.github.com

GITLAB_TOKEN=
GITLAB_WEBHOOK_SECRET=${GITLAB_SECRET}
GITLAB_API_URL=https://gitlab.com/api/v4

BITBUCKET_TOKEN=
BITBUCKET_WEBHOOK_SECRET=${BITBUCKET_SECRET}
BITBUCKET_API_URL=https://api.bitbucket.org/2.0

FORGEJO_TOKEN=
FORGEJO_WEBHOOK_SECRET=${FORGEJO_SECRET}
FORGEJO_WEB_URL=https://codeberg.org
FORGEJO_API_URL=https://codeberg.org/api/v1
EOF
  chmod 600 .env
fi

mkdir -p data
DATA_OWNER="$(stat -c '%u' data)"
if [[ "$DATA_OWNER" != "1000" ]]; then
  if sudo -n true 2>/dev/null; then
    sudo chown -R 1000:1000 data
  else
    fail "The container runs as UID 1000. Run: sudo chown -R 1000:1000 data"
  fi
fi

docker compose up -d --build

HEALTH_URL="http://127.0.0.1:3847/healthz"
for _ in $(seq 1 60); do
  if curl -fsS "$HEALTH_URL" >/dev/null 2>&1; then
    break
  fi
  sleep 1
done

curl -fsS "$HEALTH_URL" >/dev/null || fail "OpenRabbit did not become healthy. Run: docker compose logs --tail=100 openrabbit"

PUBLIC_URL_VALUE="$(grep '^OPENRABBIT_PUBLIC_URL=' .env | cut -d= -f2-)"
echo
echo "OpenRabbit is healthy."
echo "Dashboard: ${PUBLIC_URL_VALUE}"
if [[ "$FIRST_RUN" == "1" ]]; then
  echo "Admin token (shown once): $(grep '^OPENRABBIT_ADMIN_TOKEN=' .env | cut -d= -f2-)"
  echo "Save this token in your password manager, then sign in at the dashboard."
else
  echo "Admin token: use the value already saved in .env."
fi
echo "Add provider tokens to .env, then run: docker compose up -d --force-recreate"
